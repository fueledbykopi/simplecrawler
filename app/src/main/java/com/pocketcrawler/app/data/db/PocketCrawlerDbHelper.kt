package com.pocketcrawler.app.data.db

import android.content.ContentValues
import android.content.Context
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteOpenHelper
import com.pocketcrawler.app.data.search.FtsQueryBuilder
import com.pocketcrawler.app.model.SavedPage
import com.pocketcrawler.app.model.SearchResult
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * Android built-in [SQLiteOpenHelper] backed by an FTS5 virtual table:
 * `CREATE VIRTUAL TABLE IF NOT EXISTS pages USING fts5(url UNINDEXED, title, content)`
 */
class PocketCrawlerDbHelper(context: Context) : SQLiteOpenHelper(
    context.applicationContext,
    DATABASE_NAME,
    null,
    DATABASE_VERSION
) {

    override fun onCreate(db: SQLiteDatabase) {
        db.execSQL(CREATE_PAGES_FTS5_TABLE)
    }

    override fun onUpgrade(db: SQLiteDatabase, oldVersion: Int, newVersion: Int) {
        db.execSQL("DROP TABLE IF EXISTS $TABLE_PAGES")
        onCreate(db)
    }

    /**
     * Inserts or replaces an indexed page in the FTS5 `pages` virtual table.
     */
    suspend fun savePage(url: String, title: String, content: String) = withContext(Dispatchers.IO) {
        val db = writableDatabase
        db.beginTransaction()
        try {
            // FTS5 virtual tables do not enforce UNIQUE on UNINDEXED columns, so deduplicate explicitly
            db.delete(TABLE_PAGES, "$COL_URL = ?", arrayOf(url))
            val values = ContentValues().apply {
                put(COL_URL, url)
                put(COL_TITLE, title)
                put(COL_CONTENT, content)
            }
            db.insertOrThrow(TABLE_PAGES, null, values)
            db.setTransactionSuccessful()
        } finally {
            db.endTransaction()
        }
    }

    /**
     * Queries the local SQLite FTS5 `pages` table completely offline, ranked by relevance
     * (`ORDER BY rank`) with highlighted snippets generated by SQLite's `snippet()` function.
     */
    suspend fun searchPages(rawQuery: String, limit: Int = 50): List<SearchResult> = withContext(Dispatchers.IO) {
        val ftsQuery = FtsQueryBuilder.build(rawQuery) ?: return@withContext emptyList()
        val db = readableDatabase

        val sql = """
            SELECT
                rowid,
                $COL_URL,
                $COL_TITLE,
                snippet($TABLE_PAGES, 2, '${FtsQueryBuilder.HIGHLIGHT_START}', '${FtsQueryBuilder.HIGHLIGHT_END}', '…', 24) AS body_snippet,
                snippet($TABLE_PAGES, 1, '${FtsQueryBuilder.HIGHLIGHT_START}', '${FtsQueryBuilder.HIGHLIGHT_END}', '…', 16) AS title_snippet,
                substr($COL_CONTENT, 1, 200) AS preview_text,
                rank
            FROM $TABLE_PAGES
            WHERE $TABLE_PAGES MATCH ?
            ORDER BY rank
            LIMIT ?
        """.trimIndent()

        val results = mutableListOf<SearchResult>()
        db.rawQuery(sql, arrayOf(ftsQuery, limit.toString())).use { cursor ->
            while (cursor.moveToNext()) {
                val rowId = cursor.getLong(0)
                val url = cursor.getString(1).orEmpty()
                val title = cursor.getString(2).orEmpty()
                val bodySnippet = cursor.getString(3).orEmpty()
                val titleSnippet = cursor.getString(4).orEmpty()
                val previewText = cursor.getString(5).orEmpty()
                val rank = cursor.getDouble(6)

                val bestSnippet = when {
                    bodySnippet.contains(FtsQueryBuilder.HIGHLIGHT_START) -> bodySnippet
                    titleSnippet.contains(FtsQueryBuilder.HIGHLIGHT_START) -> {
                        if (previewText.isNotBlank()) "$titleSnippet — $previewText" else titleSnippet
                    }
                    bodySnippet.isNotBlank() -> bodySnippet
                    else -> previewText
                }

                results.add(
                    SearchResult(
                        rowId = rowId,
                        url = url,
                        title = title,
                        highlightedSnippet = bestSnippet,
                        rank = rank
                    )
                )
            }
        }
        results
    }

    /**
     * Loads the full offline text of an indexed page for the Reader View.
     */
    suspend fun getPageByRowId(rowId: Long): SavedPage? = withContext(Dispatchers.IO) {
        val db = readableDatabase
        val sql = "SELECT rowid, $COL_URL, $COL_TITLE, $COL_CONTENT FROM $TABLE_PAGES WHERE rowid = ?"
        db.rawQuery(sql, arrayOf(rowId.toString())).use { cursor ->
            if (cursor.moveToFirst()) {
                SavedPage(
                    rowId = cursor.getLong(0),
                    url = cursor.getString(1).orEmpty(),
                    title = cursor.getString(2).orEmpty(),
                    content = cursor.getString(3).orEmpty()
                )
            } else {
                null
            }
        }
    }

    /**
     * Lists recently indexed pages for quick browsing when the search bar is empty.
     */
    suspend fun getRecentPages(limit: Int = 50): List<SavedPage> = withContext(Dispatchers.IO) {
        val db = readableDatabase
        val sql = "SELECT rowid, $COL_URL, $COL_TITLE, $COL_CONTENT FROM $TABLE_PAGES ORDER BY rowid DESC LIMIT ?"
        val pages = mutableListOf<SavedPage>()
        db.rawQuery(sql, arrayOf(limit.toString())).use { cursor ->
            while (cursor.moveToNext()) {
                pages.add(
                    SavedPage(
                        rowId = cursor.getLong(0),
                        url = cursor.getString(1).orEmpty(),
                        title = cursor.getString(2).orEmpty(),
                        content = cursor.getString(3).orEmpty()
                    )
                )
            }
        }
        pages
    }

    /**
     * Returns total number of indexed pages in the FTS5 table.
     */
    suspend fun getIndexedPageCount(): Int = withContext(Dispatchers.IO) {
        val db = readableDatabase
        db.rawQuery("SELECT COUNT(*) FROM $TABLE_PAGES", null).use { cursor ->
            if (cursor.moveToFirst()) cursor.getInt(0) else 0
        }
    }

    /**
     * Deletes all rows from the `pages` FTS5 virtual table.
     */
    suspend fun clearDatabase() = withContext(Dispatchers.IO) {
        val db = writableDatabase
        db.execSQL("DELETE FROM $TABLE_PAGES")
    }

    companion object {
        const val DATABASE_NAME = "pocket_crawler.db"
        const val DATABASE_VERSION = 1

        const val TABLE_PAGES = "pages"
        const val COL_URL = "url"
        const val COL_TITLE = "title"
        const val COL_CONTENT = "content"

        const val CREATE_PAGES_FTS5_TABLE =
            "CREATE VIRTUAL TABLE IF NOT EXISTS pages USING fts5(url UNINDEXED, title, content)"
    }
}
